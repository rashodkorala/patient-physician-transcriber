// Turns the server's contract fixtures into TypeScript that must satisfy lib/contracts.ts,
// so `npm run check:contracts` fails if the two sides drift (CDR-001, CDR-002).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, "..", "..", "server", "tests", "fixtures");
const out = join(here, "..", "lib", "generated", "contract-fixtures.ts");

const entries = [
  ["turnResult", "turn_result.json", "TurnResult"],
  ["turnCaptionFinal", "turn_caption_final.json", "TurnCaption"],
  ["turnCaptionBlocked", "turn_caption_blocked.json", "TurnCaption"],
  ["visitStatePublic", "visit_state_public.json", "VisitStatePublic"],
];

const body = entries
  .map(([name, file, type]) => {
    const json = readFileSync(join(fixtures, file), "utf8").trim();
    return `export const ${name} = ${json} satisfies ${type};`;
  })
  .join("\n\n");

const types = [...new Set(entries.map(([, , type]) => type))].join(", ");
writeFileSync(
  out,
  `// Generated by scripts/gen-contract-fixtures.mjs from server/tests/fixtures. Do not edit.\nimport type { ${types} } from "../contracts";\n\n${body}\n`,
);
console.log(`wrote ${out}`);
