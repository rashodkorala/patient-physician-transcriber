// Turns the server's contract fixtures into TypeScript that must satisfy lib/contracts.ts,
// so `npm run check:contracts` fails if the two sides drift (CDR-001 to CDR-006).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, "..", "..", "server", "tests", "fixtures");
const out = join(here, "..", "lib", "generated", "contract-fixtures.ts");

const entries = [
  ["turnResult", "turn_result.json", "TurnResult"],
  ["turnCaptionFinal", "turn_caption_final.json", "TurnCaption"],
  ["turnCaptionBlocked", "turn_caption_blocked.json", "TurnCaption"],
  ["visitStatePublic", "visit_state_public.json", "VisitStatePublic"],
  ["visitStateController", "visit_state_controller.json", "VisitStateController"],
  ["empathyNudge", "empathy_nudge.json", "EmpathyNudge"],
  ["interpreterEscalation", "interpreter_escalation.json", "InterpreterEscalation"],
  ["turnRef", "turn_ref.json", "TurnRef"],
  ["visitNames", "visit_names.json", "Names"],
  ["interpreterLine", "interpreter_line.json", "InterpreterLine"],
  ["nameProposed", "name_proposed.json", "NameProposed"],
  ["voicePlayback", "voice_playback.json", "VoicePlayback"],
  ["voiceSpeaking", "voice_speaking.json", "VoiceSpeaking"],
  ["demoInjectionState", "demo_injection_state.json", "DemoInjectionState"],
  ["markHighRisk", "mark_high_risk.json", "MarkHighRisk"],
  ["consentNotice", "consent_notice.json", "ConsentNotice"],
  ["consentState", "consent_state.json", "ConsentState"],
  ["consentSpeak", "consent_speak.json", "ConsentSpeak"],
  ["consentGive", "consent_give.json", "ConsentGive"],
  ["consentWithdraw", "consent_withdraw.json", "ConsentWithdraw"],
  ["commandRefused", "command_refused.json", "CommandRefused"],
  ["interpreterDismiss", "interpreter_dismiss.json", "InterpreterDismiss"],
  ["interpreterDismissed", "interpreter_dismissed.json", "InterpreterDismissed"],
  ["escalationEntry", "escalation_entry.json", "EscalationEntry"],
  ["injectionStatus", "injection_status.json", "InjectionStatus"],
  ["recordIntegrityBroken", "record_integrity_broken.json", "RecordIntegrity"],
];

const body = entries
  .map(([name, file, type]) => {
    const json = readFileSync(join(fixtures, file), "utf8").trim();
    return `export const ${name} = ${json} satisfies ${type};`;
  })
  .join("\n\n");

const types = [...new Set(entries.map(([, , type]) => type))].join(", ");
writeFileSync(
  out,
  `// Generated by scripts/gen-contract-fixtures.mjs from server/tests/fixtures. Do not edit.\nimport type { ${types} } from "../contracts";\n\n${body}\n`,
);
console.log(`wrote ${out}`);
